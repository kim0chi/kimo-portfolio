// only the names the site actually shows, so the page doesn't carry unused logos
const content = readFileSync(new URL("../lib/content.ts", import.meta.url), "utf8")
const used = Object.entries(SLUGS).filter(([name]) => content.includes(JSON.stringify(name)))

const entries = used.map(([name, slug]) => {
  const icon = icons[`si${slug.charAt(0).toUpperCase()}${slug.slice(1)}`]
  if (!icon) throw new Error(`Simple Icons has no "${slug}" (for ${name})`)
  return `  ${JSON.stringify(name)}: ${JSON.stringify(icon.path)},`
})

writeFileSync(
  new URL("../lib/tech-icons.ts", import.meta.url),
  `// Generated by scripts/tech-icons.mjs from Simple Icons (CC0); edit the script, not this file.
// SVG path data (24×24 viewBox) for each tech name shown on the site.
export const TECH_ICONS: Record<string, string> = {
${entries.join("\n")}
}
`,
)
console.log(`wrote ${entries.length} icons to lib/tech-icons.ts`)
